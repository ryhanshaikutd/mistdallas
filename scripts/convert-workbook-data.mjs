#!/usr/bin/env node
/**
 * One-time conversion of the 2027 Handbook's workbook-data.js into
 * src/lib/workbook/content.ts.
 *
 *   node scripts/convert-workbook-data.mjs /path/to/mistdallas2027handbook/workbook-data.js
 *
 * Applies the catalog fixes decided in the port plan (team names, the
 * outreach and ceremonies placements, free-text reporting lines → slugs) and
 * writes a typed TypeScript module. After generation, content.ts is edited
 * directly in git; this script documents where it came from.
 */
import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";

const TEAM_MAP = { exec: "exec", marketing: "pr", dreamteam: "dream_team", operations: "logistics" };
const PLACEMENT_FIXES = {
  outreach: { team: "pr", reportsTo: "Marketing Lead" },
  ceremonies: { team: "programs", reportsTo: "Programs Lead" },
};
const NAME_ALIASES = {
  "Internal AD": "internal-ad",
  "External AD": "external-ad",
  "Sports Lead": "sports-lead",
  "Graphic Design Coord": "graphic-design",
  "Outreach Coord": "outreach",
  "Communications Coord": "comms",
  "Food Coord": "food",
  "Ceremonies Coord": "ceremonies",
  "Hospitality Coord": "hospitality",
  "Finance Coord": "finance-coord",
  "Sponsorships Coord": "sponsorships",
  "Programs Coord": "programs-coord",
  "Sisters Sports Coord": "sports-sisters",
  "Brothers Sports Coord": "sports-brothers",
  "Sisters KQ Coord": "sisters-kq",
  "Brothers KQ Coord": "knowledge-brothers",
};
const NULL_NAMES = new Set(["MIST Nationals"]);
const DROPPED_NAMES = new Set(["All Leads", "Training & Development Coord"]);

export function loadHandbookData(source) {
  const sandbox = { window: {} };
  vm.createContext(sandbox);
  vm.runInContext(source, sandbox);
  return sandbox.window.MIST_DATA;
}

export function convert(data) {
  const byTitle = new Map(data.ROLES.map((r) => [r.title, r.id]));
  const unresolved = new Set();
  const resolve = (name) => {
    if (name == null || NULL_NAMES.has(name)) return null;
    if (DROPPED_NAMES.has(name)) return undefined;
    const expanded = name.replace(/\bCoord$/, "Coordinator");
    const slug = NAME_ALIASES[name] ?? byTitle.get(name) ?? byTitle.get(expanded);
    if (!slug) {
      unresolved.add(name);
      return undefined;
    }
    return slug;
  };

  const roles = {};
  for (const r of data.ROLES) {
    const fix = PLACEMENT_FIXES[r.id] ?? {};
    const phases = {};
    for (const phase of ["foundations", "build", "stabilization", "execution"]) {
      const p = r.phases[phase];
      if (!p) throw new Error(`${r.id} is missing phase ${phase}`);
      phases[phase] = {
        focus: p.focus ?? "",
        responsibilities: p.responsibilities ?? [],
        deliverables: p.deliverables ?? [],
        frameworks: (p.frameworks ?? []).map((f) => {
          if (f.type !== "table") throw new Error(`${r.id}: unsupported framework type ${f.type}`);
          return { type: "table", title: f.title, columns: f.columns, rows: f.rows ?? 4 };
        }),
        weeklyPlan: p.weeklyPlan ?? [],
        reflections: p.reflections ?? [],
        risks: p.risks ?? [],
      };
    }
    roles[r.id] = {
      slug: r.id,
      title: r.title,
      team: fix.team ?? TEAM_MAP[r.team] ?? r.team,
      startPhase: r.startPhase,
      badge: r.badge ?? "",
      reportsTo: resolve(fix.reportsTo ?? r.reportsTo) ?? null,
      manages: (r.manages ?? []).map(resolve).filter((s) => s !== undefined && s !== null),
      phases,
    };
  }

  if (unresolved.size) throw new Error(`Unresolved role names: ${[...unresolved].join(", ")}`);

  // Keep "manages" consistent with the placement fixes.
  for (const slug of Object.keys(PLACEMENT_FIXES)) {
    const boss = roles[slug].reportsTo;
    for (const role of Object.values(roles)) {
      role.manages = role.manages.filter((m) => m !== slug);
    }
    if (boss && !roles[boss].manages.includes(slug)) roles[boss].manages.push(slug);
  }

  const phaseMeta = {};
  for (const [id, m] of Object.entries(data.PHASE_META)) {
    phaseMeta[id] = { id, label: m.label, shortLabel: m.shortLabel, dates: m.dates, tagline: m.tagline, color: m.color };
  }

  return { phaseMeta, boardStandard: data.BOARD_STANDARD, roles };
}

export function renderTs({ phaseMeta, boardStandard, roles }) {
  const j = (v) => JSON.stringify(v, null, 2);
  return `// Generated by scripts/convert-workbook-data.mjs from the 2027 Handbook's workbook-data.js.
// Edit this file directly from now on; the generator is kept only to document the source.
import type { PhaseId, PhaseMeta, RoleWorkbook } from "./types";

export const PHASE_META: Record<PhaseId, PhaseMeta> = ${j(phaseMeta)};

export const BOARD_STANDARD: string[] = ${j(boardStandard)};

export const WORKBOOK_ROLES: Record<string, RoleWorkbook> = ${j(roles)};

/** The workbook for a seat slug, or null when the seat has no workbook (e.g. dream-team). */
export function workbookFor(slug: string | null | undefined): RoleWorkbook | null {
  if (!slug) return null;
  return WORKBOOK_ROLES[slug] ?? null;
}
`;
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(new URL(import.meta.url).pathname)) {
  const input = process.argv[2];
  if (!input) {
    console.error("usage: convert-workbook-data.mjs <path-to-workbook-data.js>");
    process.exit(1);
  }
  const data = loadHandbookData(fs.readFileSync(input, "utf8"));
  const out = path.resolve("src/lib/workbook/content.ts");
  fs.writeFileSync(out, renderTs(convert(data)));
  console.error(`wrote ${out}: ${Object.keys(data.ROLES).length} roles`);
}
