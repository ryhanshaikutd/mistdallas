/**
 * Pure mapping helpers for scripts/sync-handbook-data.mjs (plain JS so the
 * script runs on any Node 20+ without a TypeScript loader).
 *
 * deliverableId / deliverableIds mirror src/lib/workbook/progress.ts exactly;
 * scripts/lib/handbook-map.test.mjs asserts they agree.
 */

export const LEGACY_SLUG_ALIASES = { groups: "group-projects", communications: "comms" };
const BOARD_DOMAIN = "getmistified.com";

function editDistance(a, b) {
  const dp = Array.from({ length: a.length + 1 }, (_, i) => [i, ...Array(b.length).fill(0)]);
  for (let j = 1; j <= b.length; j++) dp[0][j] = j;
  for (let i = 1; i <= a.length; i++) {
    for (let j = 1; j <= b.length; j++) {
      dp[i][j] = Math.min(dp[i - 1][j] + 1, dp[i][j - 1] + 1, dp[i - 1][j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1));
    }
  }
  return dp[a.length][b.length];
}

/** Handbook profile row → legacy_seat_assignments row (+ optional warning). */
export function mapProfile(row, knownSlugs) {
  const email = String(row.email ?? "").trim().toLowerCase();
  const fullName = row.full_name == null ? null : String(row.full_name).trim() || null;
  const out = { email, full_name: fullName, position_slug: null, is_admin: !!row.is_admin };
  const warnings = [];

  const domain = email.split("@")[1] ?? "";
  if (domain && domain !== BOARD_DOMAIN && editDistance(domain, BOARD_DOMAIN) <= 2) {
    warnings.push(`email domain looks misspelled (${domain}); it will not match a @${BOARD_DOMAIN} Google account`);
  }
  if (row.role_id) {
    const slug = LEGACY_SLUG_ALIASES[row.role_id] ?? row.role_id;
    if (knownSlugs.has(slug)) out.position_slug = slug;
    else warnings.push(`unknown role_id ${row.role_id}`);
  }
  if (warnings.length) out.warning = warnings.join("; ");
  return out;
}

function fnv1a(input) {
  let h = 0x811c9dc5;
  for (let i = 0; i < input.length; i++) {
    h ^= input.charCodeAt(i);
    h = Math.imul(h, 0x01000193) >>> 0;
  }
  return h.toString(16).padStart(8, "0");
}
const normalize = (text) => text.trim().replace(/\s+/g, " ").toLowerCase();

export function deliverableId(text, ordinal = 0) {
  const base = `d-${fnv1a(normalize(text))}`;
  return ordinal > 0 ? `${base}-${ordinal}` : base;
}

export function deliverableIds(deliverables) {
  const seen = new Map();
  return deliverables.map((text) => {
    const key = normalize(text);
    const ordinal = seen.get(key) ?? 0;
    seen.set(key, ordinal + 1);
    return deliverableId(text, ordinal);
  });
}

/**
 * Handbook workbook_progress row (index-aligned checks) → legacy_workbook_progress
 * row keyed by deliverable id. Returns null when the owner has no seat.
 */
export function mapWorkbookRow(row, profilesById, roles) {
  const profile = profilesById.get(row.user_id);
  if (!profile || !profile.position_slug) return null;
  const deliverables = roles[profile.position_slug]?.[row.phase] ?? [];
  const ids = deliverableIds(deliverables);
  const checks = {};
  (row.data?.checks ?? []).forEach((checked, i) => {
    if (checked === true && ids[i]) checks[ids[i]] = true;
  });
  return {
    email: profile.email,
    position_slug: profile.position_slug,
    phase: row.phase,
    data: { checks, notes: row.data?.notes ?? "", fields: { ...(row.data?.fields ?? {}) } },
    percent_complete: row.percent_complete ?? 0,
    updated_at: row.updated_at ?? null,
  };
}

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);

/** Idempotent SQL for both legacy tables. */
export function toSql(seats, progress) {
  const parts = ["-- Generated by scripts/sync-handbook-data.mjs. Contains personal data: keep out of git."];
  if (seats.length) {
    parts.push(
      "insert into legacy_seat_assignments (email, full_name, position_slug, is_admin, source) values",
      seats.map((s) => `  (${q(s.email)}, ${q(s.full_name)}, ${q(s.position_slug)}, ${s.is_admin ? "true" : "false"}, 'handbook-2027')`).join(",\n"),
      "on conflict (email) do update set full_name = excluded.full_name, position_slug = excluded.position_slug, is_admin = excluded.is_admin, source = excluded.source;"
    );
  }
  if (progress.length) {
    parts.push(
      "insert into legacy_workbook_progress (email, position_slug, phase, data, percent_complete, updated_at) values",
      progress
        .map((p) => `  (${q(p.email)}, ${q(p.position_slug)}, ${q(p.phase)}, ${q(JSON.stringify(p.data))}::jsonb, ${Number(p.percent_complete) || 0}, ${q(p.updated_at)})`)
        .join(",\n"),
      "on conflict (email, position_slug, phase) do update set data = excluded.data, percent_complete = excluded.percent_complete, updated_at = excluded.updated_at;"
    );
  }
  parts.push("select public.apply_legacy_seats_all();");
  return parts.join("\n") + "\n";
}

/** slug → phase → deliverables, read from the generated content.ts (its data is plain JSON). */
export function extractDeliverables(contentTs) {
  const marker = contentTs.indexOf("export const WORKBOOK_ROLES");
  if (marker < 0) throw new Error("WORKBOOK_ROLES not found in content.ts");
  const start = contentTs.indexOf("{", marker);
  const end = contentTs.indexOf("\n};", start);
  const roles = JSON.parse(contentTs.slice(start, end + 2));
  const out = {};
  for (const [slug, role] of Object.entries(roles)) {
    out[slug] = Object.fromEntries(Object.entries(role.phases).map(([phase, p]) => [phase, p.deliverables ?? []]));
  }
  return out;
}
